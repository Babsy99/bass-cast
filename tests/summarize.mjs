// Builds tests/results/RESULTS.md from the JSON the test runner wrote (no hand-entered numbers).
import fs from 'node:fs';
// Either one full run (summary.json) or section runs (ONLY=basic / pair / lat) merged, newest wins per key.
const part = (n) => (fs.existsSync(`tests/results/${n}.json`) ? JSON.parse(fs.readFileSync(`tests/results/${n}.json`, 'utf8')) : null);
const parts = ['summary', 'summary-basic', 'summary-pair', 'summary-lat'].map((n) => [n, part(n)]).filter(([, x]) => x)
  .sort((a, b) => Date.parse(a[1].finishedAt) - Date.parse(b[1].finishedAt));
const R = Object.assign({}, ...parts.map(([, x]) => x));
R.consoleErrors = { count: parts.reduce((n, [, x]) => n + (x.consoleErrors?.count ?? 0), 0) };
R.sources = parts.map(([n, x]) => `${n}.json (${x.finishedAt})`).join(', ');
const E = R.b0aExpired ? R : JSON.parse(fs.readFileSync('tests/results/summary-expired.json', 'utf8'));
const U = fs.existsSync('tests/results/detector-unit.json') ? JSON.parse(fs.readFileSync('tests/results/detector-unit.json', 'utf8')) : null;
const M = R.motion || {};
const L = R.latency, c = R.syntheticCasts, rc = R.reconnect;
const lat = (n, x) => `| ${n} | ${x.path} (${Object.entries(x.linkTags || {}).map(([k, v]) => `${k}×${v}`).join(', ')}) | ${x.casts} | ${x.lagMedianMs} | ${x.lagP95Ms} | ${x.detectMedianMs} / ${x.detectP95Ms} | ${x.rttHalfMedianMs} / ${x.rttHalfP95Ms} | ${x.deliveryAgeMedianMs} / ${x.deliveryAgeP95Ms} | \`${x.file}\` |`;
const md = `Generated by \`node tests/summarize.mjs\` from ${R.sources}.
Console errors across the run: **${R.consoleErrors.count}** (expired run: ${E.consoleErrors.count}). Renderer in headless Chrome: \`${R.renderer.overlay}\` (${R.renderer.why}).

**Detector unit tests** (\`node tests/detector-unit.mjs\` → \`detector-unit.json\`): **${U ? `${U.pass}/${U.pass + U.fail}` : 'not run'}**
${U ? U.results.map((r) => `- ${r.ok ? '✓' : '✗'} ${r.name}`).join('\n') : ''}

**Motion casting end to end** (\`summary.json → motion\`; fresh host each, empty storage, no button, realistic iPhone-like traces with tremor, cross-axis coupling and 60 Hz jitter)

| grip (axis, backswing sign) | 1st swing 400°/s | 300°/s | 500°/s | learned | auto power scale |
|---|---|---|---|---|---|
${Object.entries(M).map(([k, m]) => `| ${k} | ${(+m.first400.power).toFixed(2)} → ${m.first400.distFt} ft | ${(+m.at300.power).toFixed(2)} → ${m.at300.distFt} ft | ${(+m.at500.power).toFixed(2)} → ${m.at500.distFt} ft | ${'XYZ'[m.learned?.axis]}${m.learned?.sign > 0 ? '+' : '−'} (saved: ${m.persisted}) | max at ${m.autoScale.wMax}°/s |`).join('\n')}

${M['X+']?.rejects ? `Rejects (all logged in the cast export with reason and raw peaks; export attempt stats ${JSON.stringify(M['X+'].exportHasAttempts.stats)}):
- weak flick → \`${M['X+'].rejects.weak.map((a) => `${a.reason}: "${a.coach}" back ${a.backPeak} / flick ${a.fwdPeak} °/s, x/y/z ${a.axisPeaks.join('/')}`).join('; ')}\` (phone showed "${M['X+'].rejects.padCoachAfterWeak}")
- button held 650 ms after the flick → \`${M['X+'].rejects.heldTooLong.map((a) => `${a.reason}: "${a.coach}"`).join('; ')}\`
- button let go during the backswing, no flick → \`${M['X+'].rejects.releasedEarly.map((a) => `${a.reason}: "${a.coach}"`).join('; ')}\`

Lag proof: phone flashes ${M['X+'].lagProof.padFlashes}, Mac flashes ${M['X+'].lagProof.hostFlashes}, gap between them ${M['X+'].lagProof.flashGapMs} ms (measured lag for that cast ${M['X+'].lagProof.measuredLagMs} ms, link ${M['X+'].lagProof.link}).` : ''}

**Synthetic casts on the main host** (\`summary.json → syntheticCasts\`; good > weak and good > late: ${c.orderOk ? 'OK' : 'FAIL'})

| cast | distance | power | peak | release vs peak | launch angle |
|---|---|---|---|---|---|
${['weak', 'goodNoButton', 'lateButton320ms', 'earlyButtonMinus60ms', 'aimedRight12'].map((k) => `| ${k} | ${c[k].distFt} ft | ${(+c[k].power).toFixed(3)} | ${c[k].peak_dps}°/s | ${c[k].releaseDtMs} ms (${c[k].timing}) | ${c[k].launchDeg}°${k === 'aimedRight12' ? `, landed ${c[k].landAimDeg}° right` : ''} |`).join('\n')}

Touch-cast: pad ${R.touchCastPad.distFt} ft, host mouse ${R.touchCastHostMouse.distFt} ft.

**Test 10 casts** (\`test10-casts.json\`): **${R.test10.score}** counted. Rule: lands within ±15% and inside the aim cone, peak ≤ 500°/s, and 👍 "felt relaxed" tapped on the pad. The script threw cast 3 at 640°/s and answered 👎 on cast 5 to exercise the rule (rule check: ${R.test10.ruleOk ? 'OK' : 'FAIL'}).

| # | target | landed | peak | miss | relaxed | counts |
|---|---|---|---|---|---|---|
${R.test10.rows.map((r, i) => `| ${i + 1} | ${r.intendedFt} ft | ${r.distFt} ft | ${r.peak_dps}°/s${r.tooHard ? " (too hard, doesn't count)" : ''} | ${r.good ? 'on target' : r.missText} | ${r.relaxed === true ? '👍' : r.relaxed === false ? '👎' : '–'} | ${r.counts ? '✅' : '❌'} |`).join('\n')}

**5 fresh pairings** (\`summary.json → pairings\`): **${R.pairingSummary.success}**

| # | setup screen first | tap → connected | Show QR → first cast | pad joined → first cast | path |
|---|---|---|---|---|---|
${R.pairings.map((p, i) => `| ${i + 1} | ${p.setupShown} | ${p.tapToConnectedMs} ms | ${p.qrToFirstCastMs} ms | ${p.scanToFirstCastMs} ms | ${p.path} |`).join('\n')}

Median tap → connected ${R.pairingSummary.tapToConnectedMedianMs} ms; median QR → first cast ${R.pairingSummary.qrToFirstCastMedianMs} ms (max ${R.pairingSummary.max} ms; pass ≤ 10 000 ms). The 3 s in each connect is the WebRTC grace before the MQTT fallback, because WebRTC can't connect on this box.

**Reconnect** (\`summary.json → reconnect\`)

| test | result |
|---|---|
| 1. phone sleeps 30 s, network drops, wakes | host showed "${rc.sleep.hostDuringSleep}", Tap to resume shown: ${rc.sleep.tapToResumeShown}, wake → controlling **${rc.sleep.wakeToControllingMs} ms**, cast after: ${rc.sleep.castAfter} ft |
| 2. pad page reload (iOS drops motion permission) | button "${rc.reload.button}", tap → controlling **${rc.reload.tapToControllingMs} ms**, cast after: ${rc.reload.castAfter} ft |
| 3. camera-scan context, empty storage (pairing only in URL fragment) | tap → controlling **${rc.cameraContext.tapToControllingMs} ms**, cast after: ${rc.cameraContext.castAfter} ft |
| extra: data channel killed | frames back after ${rc.killChannel.framesBackAfterMs} ms, cast after: ${rc.killChannel.castAfter} ft |
| extra: game (host) reload | still paired: ${rc.hostReload.ok}, ${rc.hostReload.ms} ms |

3/3 reconnects without a rescan; all under the 5 s bar.

**B0a** — used code: pad \`${R.b0a.padState}\`, host log \`${R.b0a.hostLog.join('; ')}\`. Expired code: pad \`${E.b0aExpired.padState}\` ("${E.b0aExpired.padText}"), host log \`${E.b0aExpired.hostLog.join('; ')}\`.

**Cast latency, 50 casts each** (ms; lag = flick on phone → first frame showing the rod whip, in host time via clock sync)

| run | path (per-row link tags) | casts | lag median | lag p95 | detect med / p95 | ping RTT/2 med / p95 | delivery age med / p95 | file |
|---|---|---|---|---|---|---|---|---|
${lat('MQTT relay, normal (local broker)', L.mqttLocal)}
${lat('MQTT relay, throttled: pad +150 ms each way, 5% loss', L.mqttThrottled)}
| Direct WebRTC, normal / throttled | — | 0 | not measurable here (box Chrome policy blocks UDP WebRTC) | | | | | |

${R.note ? R.note + '\n' : ''}Proxy stats: ${L.proxyStats.lostChunks}/${L.proxyStats.chunks} chunks held as "lost". Every lag row carries a link tag (direct / relay / local) and, on WebRTC, the ICE pair.
About 50 ms of every lag figure is the detector itself: it confirms the flick when pitch rate falls to 80% of its peak.
Pass bar: median ≤ 100 ms, p95 ≤ 150 ms. Normal relay passes. The throttled relay fails, as expected for a phone on a bad network.
`;
fs.writeFileSync('tests/results/RESULTS.md', '# Headless test results\n\n' + md);
const p = fs.readFileSync('PAIRING.md', 'utf8');
if (p.includes('RESULTS_PLACEHOLDER')) fs.writeFileSync('PAIRING.md', p.replace('RESULTS_PLACEHOLDER', md));
console.log('ok');
